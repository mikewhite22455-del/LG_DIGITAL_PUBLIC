package com.example.core

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.contentOrNull
import java.io.ByteArrayOutputStream

enum class QrExchangeTarget(val id: String, val displayName: String) {
    AUTO("auto", "Auto-Detect"),
    KRAKEN("kraken", "Kraken Pro"),
    COINBASE("coinbase", "Coinbase"),
    KUCOIN("kucoin", "KuCoin"),
    BITSTAMP("bitstamp", "Bitstamp"),
    LG_SERVER("lg_server", "LG Token");

    companion object {
        fun fromId(id: String?): QrExchangeTarget = when (id?.trim()?.lowercase()) {
            "kraken", "krakenpro", "kraken_pro" -> KRAKEN
            "coinbase", "cb", "coinbasepro", "coinbase_advanced" -> COINBASE
            "kucoin", "kucoin_spot" -> KUCOIN
            "bitstamp" -> BITSTAMP
            "lg_server", "lgdigital", "lg-digital", "render", "server" -> LG_SERVER
            else -> AUTO
        }
    }
}

data class ParsedExchangeQrCredentials(
    val exchangeId: String,
    val exchangeDisplayName: String,
    val apiKey: String = "",
    val apiSecret: String = "",
    val passphrase: String = "",
    val lgServerToken: String = "",
    val formatLabel: String = ""
) {
    val isCompleteForExchange: Boolean
        get() = when (exchangeId) {
            "kucoin" -> apiKey.isNotBlank() && apiSecret.isNotBlank() && passphrase.isNotBlank()
            "lg_server" -> lgServerToken.isNotBlank()
            else -> apiKey.isNotBlank() && apiSecret.isNotBlank()
        }

    fun reassignedTo(target: QrExchangeTarget): ParsedExchangeQrCredentials {
        if (target == QrExchangeTarget.AUTO) return this
        return if (target == QrExchangeTarget.LG_SERVER) {
            val token = lgServerToken.ifBlank { apiKey.ifBlank { apiSecret } }
            copy(
                exchangeId = target.id,
                exchangeDisplayName = target.displayName,
                lgServerToken = token
            )
        } else {
            copy(
                exchangeId = target.id,
                exchangeDisplayName = target.displayName
            )
        }
    }
}

sealed interface QrCredentialParseResult {
    data class Success(val credentials: ParsedExchangeQrCredentials) : QrCredentialParseResult
    data class Invalid(val reason: String) : QrCredentialParseResult
}

/**
 * Pure on-device parser for API credential QR codes generated by Kraken Pro, Coinbase Advanced / CDP,
 * KuCoin, Bitstamp, and LG Digital Render portals.
 *
 * Security invariants:
 * - Never logs raw QR content or extracted credentials.
 * - Rejects oversized payloads and non-credential web URLs.
 * - Preserves literal '+' characters in Base64 secrets during percent-decoding.
 */
object ExchangeQrCredentialParser {

    private const val MAX_PAYLOAD_CHARS = 8192

    private val lenientJson = Json {
        ignoreUnknownKeys = true
        isLenient = true
    }

    fun parse(
        rawPayload: String,
        preferredTarget: QrExchangeTarget = QrExchangeTarget.AUTO
    ): QrCredentialParseResult {
        val trimmed = rawPayload.trim()
        if (trimmed.isEmpty()) {
            return QrCredentialParseResult.Invalid("Empty QR payload.")
        }
        if (trimmed.length > MAX_PAYLOAD_CHARS) {
            return QrCredentialParseResult.Invalid("QR payload exceeds safe credential size limit.")
        }

        // 1. JSON object payloads (Coinbase CDP JSON, KuCoin JSON, Kraken/Bitstamp JSON exports)
        if (trimmed.startsWith("{") && trimmed.endsWith("}")) {
            parseJson(trimmed, preferredTarget)?.let { return it }
        }

        // 2. URI / Deep-link / Query-string payloads (e.g., kraken://apikey?key=...&secret=...)
        if (trimmed.contains("://") || looksLikeQueryString(trimmed)) {
            parseUriOrQuery(trimmed, preferredTarget)?.let { return it }
        }

        // 3. Key-value lines (API_KEY=..., API_SECRET=..., PASSPHRASE=...)
        if (trimmed.contains("=") && (trimmed.contains("\n") || trimmed.contains(";"))) {
            parseKeyValueLines(trimmed, preferredTarget)?.let { return it }
        }

        // 4. Multi-line or delimited payloads (KEY\nSECRET[\nPASSPHRASE] or key:secret[:passphrase])
        parseDelimited(trimmed, preferredTarget)?.let { return it }

        // 5. Explicit LG Server Bearer Token fallback
        if (preferredTarget == QrExchangeTarget.LG_SERVER &&
            !trimmed.startsWith("http://", ignoreCase = true) &&
            !trimmed.startsWith("https://", ignoreCase = true) &&
            trimmed.length >= 8 &&
            !trimmed.any { it.isWhitespace() }
        ) {
            return QrCredentialParseResult.Success(
                ParsedExchangeQrCredentials(
                    exchangeId = QrExchangeTarget.LG_SERVER.id,
                    exchangeDisplayName = QrExchangeTarget.LG_SERVER.displayName,
                    lgServerToken = trimmed,
                    formatLabel = "Bearer Token QR"
                )
            )
        }

        return QrCredentialParseResult.Invalid(
            "Unrecognized QR format. Scan an API key QR code from Kraken Pro, Coinbase Advanced, KuCoin, or Bitstamp."
        )
    }

    private fun parseJson(
        payload: String,
        preferredTarget: QrExchangeTarget
    ): QrCredentialParseResult? {
        val obj = runCatching {
            lenientJson.parseToJsonElement(payload) as? JsonObject
        }.getOrNull() ?: return QrCredentialParseResult.Invalid("Malformed JSON in QR code.")

        val map = LinkedHashMap<String, String>()
        for ((k, v) in obj) {
            val str = (v as? JsonPrimitive)?.contentOrNull?.trim()
            if (!str.isNullOrEmpty()) {
                map[normalizeKey(k)] = str
            }
        }

        val explicitExchange = firstMatch(map, "exchange", "venue", "platform", "provider", "broker")
        val apiKey = firstMatch(
            map,
            "apikey", "key", "publickey", "keyid", "accesskey", "name", "id", "clientid"
        )
        val apiSecret = firstMatch(
            map,
            "apisecret", "secret", "secretkey", "privatekey", "privkey", "jwt", "token"
        )
        val passphrase = firstMatch(
            map,
            "passphrase", "apipassphrase", "pass", "password"
        )
        val lgToken = firstMatch(
            map,
            "lgservertoken", "servertoken", "bearertoken", "bearer"
        )

        if (apiKey.isEmpty() && apiSecret.isEmpty() && lgToken.isEmpty()) {
            return QrCredentialParseResult.Invalid("JSON QR code does not contain API key or secret fields.")
        }

        val resolvedTarget = resolveTarget(
            preferred = preferredTarget,
            explicitHint = explicitExchange,
            apiKey = apiKey,
            apiSecret = apiSecret,
            passphrase = passphrase,
            hasOnlyBearerToken = lgToken.isNotEmpty() && apiKey.isEmpty()
        )

        val resolvedLgToken = when {
            lgToken.isNotEmpty() -> lgToken
            resolvedTarget == QrExchangeTarget.LG_SERVER -> apiSecret.ifEmpty { apiKey }
            else -> ""
        }

        val formatLabel = when {
            apiKey.startsWith("organizations/", ignoreCase = true) ||
                apiSecret.contains("BEGIN EC PRIVATE KEY", ignoreCase = true) -> "Coinbase CDP JSON"
            else -> "JSON Credential QR"
        }

        return QrCredentialParseResult.Success(
            ParsedExchangeQrCredentials(
                exchangeId = resolvedTarget.id,
                exchangeDisplayName = resolvedTarget.displayName,
                apiKey = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiKey,
                apiSecret = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiSecret,
                passphrase = if (resolvedTarget == QrExchangeTarget.KUCOIN) passphrase else "",
                lgServerToken = resolvedLgToken,
                formatLabel = formatLabel
            )
        )
    }

    private fun parseUriOrQuery(
        payload: String,
        preferredTarget: QrExchangeTarget
    ): QrCredentialParseResult? {
        val scheme = payload.substringBefore("://", missingDelimiterValue = "").lowercase()
        val afterScheme = if (payload.contains("://")) payload.substringAfter("://") else payload
        val hostPart = afterScheme.substringBefore("?").substringBefore("/").lowercase()
        val queryPart = when {
            payload.contains("?") -> payload.substringAfter("?").substringBefore("#")
            looksLikeQueryString(payload) -> payload
            else -> ""
        }

        if (queryPart.isEmpty()) {
            return if (scheme == "http" || scheme == "https") {
                QrCredentialParseResult.Invalid(
                    "This QR code is a web link without API credentials. Scan the exchange's API key QR code instead."
                )
            } else {
                null
            }
        }

        val params = LinkedHashMap<String, String>()
        queryPart.split("&").forEach { pair ->
            val idx = pair.indexOf('=')
            if (idx > 0) {
                val rawKey = decodePercentPreservingPlus(pair.substring(0, idx)).trim()
                val rawVal = decodePercentPreservingPlus(pair.substring(idx + 1)).trim()
                if (rawKey.isNotEmpty() && rawVal.isNotEmpty()) {
                    params[normalizeKey(rawKey)] = rawVal
                }
            }
        }

        val explicitHint = firstMatch(params, "exchange", "venue", "platform")
            .ifEmpty {
                when {
                    scheme.contains("kraken") || hostPart.contains("kraken") -> "kraken"
                    scheme.contains("coinbase") || scheme == "cb" || hostPart.contains("coinbase") -> "coinbase"
                    scheme.contains("kucoin") || hostPart.contains("kucoin") -> "kucoin"
                    scheme.contains("bitstamp") || hostPart.contains("bitstamp") -> "bitstamp"
                    scheme.contains("lgdigital") || hostPart.contains("lg-digital") -> "lg_server"
                    else -> ""
                }
            }

        val apiKey = firstMatch(params, "key", "apikey", "publickey", "name", "id", "accesskey")
        val apiSecret = firstMatch(params, "secret", "apisecret", "privatekey", "privkey", "jwt")
        val passphrase = firstMatch(params, "passphrase", "apipassphrase", "pass", "password")
        val lgToken = firstMatch(params, "lgservertoken", "servertoken", "bearer", "token")

        if (apiKey.isEmpty() && apiSecret.isEmpty() && lgToken.isEmpty()) {
            return if (scheme == "http" || scheme == "https") {
                QrCredentialParseResult.Invalid(
                    "Web link QR detected, but no API key or secret parameters were found."
                )
            } else {
                null
            }
        }

        val resolvedTarget = resolveTarget(
            preferred = preferredTarget,
            explicitHint = explicitHint,
            apiKey = apiKey,
            apiSecret = apiSecret,
            passphrase = passphrase,
            hasOnlyBearerToken = lgToken.isNotEmpty() && apiKey.isEmpty() && apiSecret.isEmpty()
        )

        val formatLabel = if (scheme.isNotEmpty() && scheme != "http" && scheme != "https") {
            "${scheme.uppercase()}:// Portal QR"
        } else {
            "Exchange URI QR"
        }

        return QrCredentialParseResult.Success(
            ParsedExchangeQrCredentials(
                exchangeId = resolvedTarget.id,
                exchangeDisplayName = resolvedTarget.displayName,
                apiKey = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiKey,
                apiSecret = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiSecret,
                passphrase = if (resolvedTarget == QrExchangeTarget.KUCOIN) passphrase else "",
                lgServerToken = if (resolvedTarget == QrExchangeTarget.LG_SERVER) {
                    lgToken.ifEmpty { apiKey.ifEmpty { apiSecret } }
                } else {
                    ""
                },
                formatLabel = formatLabel
            )
        )
    }

    private fun parseKeyValueLines(
        payload: String,
        preferredTarget: QrExchangeTarget
    ): QrCredentialParseResult? {
        val map = LinkedHashMap<String, String>()
        val entries = payload.split('\n', ';')
        for (entry in entries) {
            val idx = entry.indexOf('=')
            if (idx > 0) {
                val k = normalizeKey(entry.substring(0, idx))
                val v = entry.substring(idx + 1).trim().trim('"', '\'')
                if (k.isNotEmpty() && v.isNotEmpty()) {
                    map[k] = v
                }
            }
        }

        val explicitHint = firstMatch(map, "exchange", "venue")
        val apiKey = firstMatch(map, "apikey", "key", "krakenapikey", "coinbaseapikey", "kucoinapikey", "bitstampapikey")
        val apiSecret = firstMatch(map, "apisecret", "secret", "privatekey", "krakenapisecret", "coinbaseapisecret", "kucoinapisecret", "bitstampapisecret")
        val passphrase = firstMatch(map, "passphrase", "apipassphrase", "kucoinpassphrase")
        val lgToken = firstMatch(map, "lgservertoken", "servertoken", "token", "bearer")

        if (apiKey.isEmpty() && apiSecret.isEmpty() && lgToken.isEmpty()) return null

        val inferredFromKeyNames = when {
            map.keys.any { it.startsWith("kraken") } -> "kraken"
            map.keys.any { it.startsWith("coinbase") } -> "coinbase"
            map.keys.any { it.startsWith("kucoin") } -> "kucoin"
            map.keys.any { it.startsWith("bitstamp") } -> "bitstamp"
            else -> explicitHint
        }

        val resolvedTarget = resolveTarget(
            preferred = preferredTarget,
            explicitHint = inferredFromKeyNames,
            apiKey = apiKey,
            apiSecret = apiSecret,
            passphrase = passphrase,
            hasOnlyBearerToken = lgToken.isNotEmpty() && apiKey.isEmpty() && apiSecret.isEmpty()
        )

        return QrCredentialParseResult.Success(
            ParsedExchangeQrCredentials(
                exchangeId = resolvedTarget.id,
                exchangeDisplayName = resolvedTarget.displayName,
                apiKey = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiKey,
                apiSecret = if (resolvedTarget == QrExchangeTarget.LG_SERVER) "" else apiSecret,
                passphrase = if (resolvedTarget == QrExchangeTarget.KUCOIN) passphrase else "",
                lgServerToken = if (resolvedTarget == QrExchangeTarget.LG_SERVER) lgToken else "",
                formatLabel = "Key/Value Credential QR"
            )
        )
    }

    private fun parseDelimited(
        payload: String,
        preferredTarget: QrExchangeTarget
    ): QrCredentialParseResult? {
        if (payload.startsWith("http://", ignoreCase = true) ||
            payload.startsWith("https://", ignoreCase = true)
        ) {
            return null
        }

        val lines = payload.lines().map { it.trim() }.filter { it.isNotEmpty() }
        val parts = when {
            lines.size in 2..3 -> lines
            lines.size == 1 && payload.contains("|") -> payload.split("|").map { it.trim() }
            lines.size == 1 && payload.contains(",") -> payload.split(",").map { it.trim() }
            lines.size == 1 && payload.contains(":") -> payload.split(":").map { it.trim() }
            else -> emptyList()
        }.filter { it.isNotEmpty() }

        if (parts.size !in 2..3) return null
        if (parts[0].length < 8 || parts[1].length < 8) return null

        val apiKey = parts[0]
        val apiSecret = parts[1]
        val passphrase = parts.getOrElse(2) { "" }

        val resolvedTarget = resolveTarget(
            preferred = preferredTarget,
            explicitHint = "",
            apiKey = apiKey,
            apiSecret = apiSecret,
            passphrase = passphrase,
            hasOnlyBearerToken = false
        )

        return QrCredentialParseResult.Success(
            ParsedExchangeQrCredentials(
                exchangeId = resolvedTarget.id,
                exchangeDisplayName = resolvedTarget.displayName,
                apiKey = apiKey,
                apiSecret = apiSecret,
                passphrase = if (resolvedTarget == QrExchangeTarget.KUCOIN) passphrase else "",
                formatLabel = "Delimited Credential QR"
            )
        )
    }

    private fun resolveTarget(
        preferred: QrExchangeTarget,
        explicitHint: String,
        apiKey: String,
        apiSecret: String,
        passphrase: String,
        hasOnlyBearerToken: Boolean
    ): QrExchangeTarget {
        if (preferred != QrExchangeTarget.AUTO) return preferred
        val fromHint = QrExchangeTarget.fromId(explicitHint)
        if (fromHint != QrExchangeTarget.AUTO) return fromHint

        return when {
            hasOnlyBearerToken -> QrExchangeTarget.LG_SERVER
            apiKey.startsWith("organizations/", ignoreCase = true) ||
                apiSecret.contains("BEGIN EC PRIVATE KEY", ignoreCase = true) ||
                apiSecret.count { it == '.' } == 2 -> QrExchangeTarget.COINBASE
            passphrase.isNotEmpty() -> QrExchangeTarget.KUCOIN
            else -> QrExchangeTarget.KRAKEN
        }
    }

    private fun looksLikeQueryString(text: String): Boolean {
        val lower = text.lowercase()
        return (lower.contains("key=") || lower.contains("apikey=") || lower.contains("token=")) &&
            (lower.contains("&") || lower.contains("secret="))
    }

    private fun normalizeKey(raw: String): String =
        raw.trim().lowercase().replace("_", "").replace("-", "").replace(" ", "")

    private fun firstMatch(map: Map<String, String>, vararg keys: String): String {
        for (k in keys) {
            val v = map[k]
            if (!v.isNullOrBlank()) return v
        }
        return ""
    }

    /**
     * Percent-decodes `%XX` sequences in UTF-8 without converting literal `+` into spaces,
     * which protects unencoded Base64 secrets (such as Kraken private keys).
     */
    private fun decodePercentPreservingPlus(input: String): String {
        if (!input.contains('%')) return input
        val out = ByteArrayOutputStream(input.length)
        var i = 0
        while (i < input.length) {
            val c = input[i]
            if (c == '%' && i + 2 < input.length) {
                val hi = Character.digit(input[i + 1], 16)
                val lo = Character.digit(input[i + 2], 16)
                if (hi >= 0 && lo >= 0) {
                    out.write((hi shl 4) or lo)
                    i += 3
                    continue
                }
            }
            val bytes = c.toString().toByteArray(Charsets.UTF_8)
            out.write(bytes)
            i++
        }
        return out.toString(Charsets.UTF_8.name())
    }
}
